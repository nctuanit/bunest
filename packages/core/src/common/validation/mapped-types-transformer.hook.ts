import { MetadataRegistry } from "../metadata/metadata-registry";
import {
  registerMappedTypeMetadataHook,
  type MappedTypeMetadataHook,
} from "../mapped-types/mapped-types.utils";

interface ClassTransformerMetadataEntry {
  target: Function;
  propertyName?: string;
  [key: string]: unknown;
}

interface ClassTransformerStorageLike {
  _typeMetadatas?: Map<
    Function,
    Map<string | undefined, ClassTransformerMetadataEntry>
  >;
  _transformMetadatas?: Map<
    Function,
    Map<string | undefined, ClassTransformerMetadataEntry[]>
  >;
  _exposeMetadatas?: Map<
    Function,
    Map<string | undefined, ClassTransformerMetadataEntry>
  >;
  _excludeMetadatas?: Map<
    Function,
    Map<string | undefined, ClassTransformerMetadataEntry>
  >;
  addTypeMetadata?(meta: ClassTransformerMetadataEntry): void;
  addTransformMetadata?(meta: ClassTransformerMetadataEntry): void;
  addExposeMetadata?(meta: ClassTransformerMetadataEntry): void;
  addExcludeMetadata?(meta: ClassTransformerMetadataEntry): void;
  cloneClassMetadata?(
    source: Function,
    target: Function,
    propertyFilter?: (propertyName: string) => boolean,
    stackTransforms?: boolean,
  ): string[];
}

const HOOK_INSTALLED_SYMBOL = Symbol.for(
  "bunest:validation:class_transformer_mapped_types_hook",
);
const CT_CLONED_REGISTRY_KEY = Symbol.for("bunest:mapped_types:ct_cloned");

function markStorageClonedOnce(
  source: Function,
  target: Function,
  storage: object,
): boolean {
  const g = globalThis as Record<PropertyKey, unknown>;
  let byTarget = g[CT_CLONED_REGISTRY_KEY] as
    WeakMap<Function, WeakMap<Function, WeakSet<object>>> | undefined;
  if (!byTarget) {
    byTarget = new WeakMap();
    g[CT_CLONED_REGISTRY_KEY] = byTarget;
  }
  let bySource = byTarget.get(target);
  if (!bySource) {
    bySource = new WeakMap();
    byTarget.set(target, bySource);
  }
  let storages = bySource.get(source);
  if (!storages) {
    storages = new WeakSet();
    bySource.set(source, storages);
  }
  if (storages.has(storage)) {
    return false;
  }
  storages.add(storage);
  return true;
}

function tryLoadModule(specifier: string): unknown {
  const bases = [import.meta.dir, process.cwd()];
  for (let i = 0; i < bases.length; i++) {
    const base = bases[i];
    if (!base) continue;
    try {
      const resolved = Bun.resolveSync(specifier, base);
      return require(resolved);
    } catch {
      // Try next resolution root
    }
  }
  return undefined;
}

function resolveClassTransformerStorages(): ClassTransformerStorageLike[] {
  const storages: ClassTransformerStorageLike[] = [];
  const seen = new Set<unknown>();

  // 1. Bunest native single-realm storage (ADR-015)
  const nativeStorage = (globalThis as Record<PropertyKey, unknown>)[
    Symbol.for("bunest:class-transformer:storage")
  ] as ClassTransformerStorageLike | undefined;
  if (nativeStorage && typeof nativeStorage === "object") {
    seen.add(nativeStorage);
    storages.push(nativeStorage);
  }

  for (const specifier of [
    "class-transformer/cjs/storage",
    "class-transformer/esm5/storage",
  ]) {
    const mod = tryLoadModule(specifier) as
      | {
          defaultMetadataStorage?: ClassTransformerStorageLike;
        }
      | undefined;
    const storage = mod?.defaultMetadataStorage;
    if (storage && typeof storage === "object" && !seen.has(storage)) {
      seen.add(storage);
      storages.push(storage);
    }
  }

  return storages;
}

function cloneEntry(
  entry: ClassTransformerMetadataEntry,
  target: Function,
): ClassTransformerMetadataEntry {
  return {
    ...entry,
    target,
    ...(entry.options && typeof entry.options === "object"
      ? { options: { ...(entry.options as Record<string, unknown>) } }
      : {}),
  };
}

/**
 * Mapped-type metadata hook that clones `class-transformer` `@Type()`, `@Expose()`,
 * `@Exclude()`, and `@Transform()` property metadata onto DTOs generated by
 * `PartialType`, `PickType`, `OmitType`, `IntersectionType`, and `CompositionType`.
 */
export const classTransformerMappedTypeHook: MappedTypeMetadataHook = ({
  source,
  target,
  propertyFilter,
}) => {
  const storages = resolveClassTransformerStorages();
  if (storages.length === 0) {
    return;
  }

  const filter = propertyFilter ?? (() => true);
  const chain = MetadataRegistry.getPrototypeChain(source);

  for (const storage of storages) {
    if (!markStorageClonedOnce(source, target, storage)) {
      continue;
    }
    if (typeof storage.cloneClassMetadata === "function") {
      storage.cloneClassMetadata(source, target, filter, true);
      continue;
    }
    for (const ctor of chain) {
      const typeMap = storage._typeMetadatas?.get(ctor);
      if (typeMap && typeof storage.addTypeMetadata === "function") {
        for (const [prop, meta] of typeMap.entries()) {
          if (prop !== undefined && filter(prop)) {
            storage.addTypeMetadata(cloneEntry(meta, target));
          }
        }
      }

      const transformMap = storage._transformMetadatas?.get(ctor);
      if (transformMap && typeof storage.addTransformMetadata === "function") {
        for (const [prop, list] of transformMap.entries()) {
          if (prop !== undefined && filter(prop)) {
            for (const meta of list) {
              storage.addTransformMetadata(cloneEntry(meta, target));
            }
          }
        }
      }

      const exposeMap = storage._exposeMetadatas?.get(ctor);
      if (exposeMap && typeof storage.addExposeMetadata === "function") {
        for (const [prop, meta] of exposeMap.entries()) {
          if (prop === undefined || filter(prop)) {
            storage.addExposeMetadata(cloneEntry(meta, target));
          }
        }
      }

      const excludeMap = storage._excludeMetadatas?.get(ctor);
      if (excludeMap && typeof storage.addExcludeMetadata === "function") {
        for (const [prop, meta] of excludeMap.entries()) {
          if (prop === undefined || filter(prop)) {
            storage.addExcludeMetadata(cloneEntry(meta, target));
          }
        }
      }
    }
  }
};

/**
 * Idempotently installs the `class-transformer` metadata cloning hook into
 * `@bunest/core`'s mapped-types registry.
 */
export function registerClassTransformerMappedTypeHook(): void {
  const g = globalThis as Record<PropertyKey, unknown>;
  if (g[HOOK_INSTALLED_SYMBOL]) {
    return;
  }
  g[HOOK_INSTALLED_SYMBOL] = true;
  registerMappedTypeMetadataHook(classTransformerMappedTypeHook);
}

registerClassTransformerMappedTypeHook();
