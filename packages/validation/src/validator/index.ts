/**
 * Self-register Bunest's native validator engine on globalThis so `@bunest/core`
 * (`ValidationPipe`, `mapped-types`, `config`, `i18n`) and `@bunest/swagger` resolve
 * it in O(1) with zero circular package dependencies.
 */
const BUNEST_VALIDATOR_ENGINE_SYMBOL = Symbol.for(
  "bunest:class-validator:engine",
);
const BUNEST_VALIDATOR_PACKAGE_SYMBOL = Symbol.for(
  "bunest:class-validator:package",
);

const nativeValidatorEngine = {
  Validator,
  validate,
  validateSync,
  validateOrReject,
  validateMaybeSync,
  canValidateSynchronously,
  getMetadataStorage,
  IsOptional,
  IsDefined,
  ValidateIf,
  Allow,
  ValidationError,
};

const g = globalThis as Record<PropertyKey, unknown>;
g[BUNEST_VALIDATOR_ENGINE_SYMBOL] = nativeValidatorEngine;
g[BUNEST_VALIDATOR_PACKAGE_SYMBOL] = nativeValidatorEngine;

export default nativeValidatorEngine;
