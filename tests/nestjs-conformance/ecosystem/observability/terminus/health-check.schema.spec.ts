import "reflect-metadata";
import { afterAll, beforeAll, expect, it } from "bun:test";
import {
  Controller,
  Get,
  METADATA_KEYS,
  MetadataRegistry,
  Module,
  type HeaderMetadata,
} from "../../../../../packages/common/src";
import { NestFactory } from "../../../../../packages/core/src";
import {
  HEALTH_CHECK_METADATA,
  HealthCheck,
} from "../../../../../packages/observability/src";
import {
  DocumentBuilder,
  SwaggerModule,
  type OpenAPIObject,
} from "../../../../../packages/swagger/src";
import {
  describeConformance,
  itAdapted,
} from "../../../_helpers/index";

@Controller("health")
class TestController {
  @Get()
  @HealthCheck()
  check() {
    return { status: "ok", info: {}, error: {}, details: {} };
  }
}

@Controller("ready")
class SecondController {
  @Get()
  @HealthCheck()
  check() {
    return { status: "ok", info: {}, error: {}, details: {} };
  }
}

@Controller("cached-health")
class CustomOptionsController {
  @Get()
  @HealthCheck({ noCache: false, swaggerDocumentation: false })
  check() {
    return { status: "ok", info: {}, error: {}, details: {} };
  }
}

@Module({
  controllers: [TestController, SecondController, CustomOptionsController],
})
class TestModule {}

describeConformance(
  "HealthCheck swagger schema",
  {
    upstreamPath: "terminus/lib/health-check/health-check.schema.spec.ts",
    category: "ADAPTED_PORT",
    adrs: ["ADR-001", "ADR-002"],
    notes:
      "Tests @HealthCheck() metadata, Cache-Control header registration, and SwaggerModule OpenAPI document generation via @bunest/swagger.",
  },
  () => {
    let document: OpenAPIObject;

    beforeAll(async () => {
      const app = await NestFactory.create(TestModule, { logger: false });
      document = SwaggerModule.createDocument(
        app,
        new DocumentBuilder().build(),
      );
      await app.close();
    });

    afterAll(() => {
      // Nothing left open; app already closed in beforeAll
    });

    /** The schema of a response of `GET <path>`, as a plain object */
    const responseSchema = (path: string, status: "200" | "503"): any =>
      (document.paths[path]?.get?.responses as any)?.[status]?.content?.[
        "application/json"
      ]?.schema;

    itAdapted(
      ["ADR-002"],
      "attaches HEALTH_CHECK_METADATA and Cache-Control header metadata on decorated routes",
      () => {
        expect(
          MetadataRegistry.get<{
            noCache: boolean;
            swaggerDocumentation: boolean;
          }>(HEALTH_CHECK_METADATA, TestController.prototype.check),
        ).toEqual({ noCache: true, swaggerDocumentation: true });

        expect(
          MetadataRegistry.get<{
            noCache: boolean;
            swaggerDocumentation: boolean;
          }>(HEALTH_CHECK_METADATA, CustomOptionsController.prototype.check),
        ).toEqual({ noCache: false, swaggerDocumentation: false });

        const headers = MetadataRegistry.get<HeaderMetadata[]>(
          METADATA_KEYS.HEADERS,
          TestController.prototype.check,
        );
        expect(headers).toContainEqual({
          name: "Cache-Control",
          value: "no-cache, no-store, must-revalidate",
        });

        const disabledHeaders = MetadataRegistry.get<HeaderMetadata[]>(
          METADATA_KEYS.HEADERS,
          CustomOptionsController.prototype.check,
        );
        expect(disabledHeaders).toBeUndefined();
      },
      "Verifies Bunest @HealthCheck() decorator metadata and noCache header behavior",
    );

    itAdapted(
      ["ADR-001"],
      "exposes @HealthCheck() routes in the OpenAPI document generated by SwaggerModule",
      () => {
        expect(document.paths["/health"]?.get).toBeDefined();
        expect(document.paths["/ready"]?.get).toBeDefined();
      },
      "Verifies SwaggerModule.createDocument() discovers @HealthCheck() endpoints",
    );

    // BUNEST_BUG: @HealthCheck() in packages/observability/src/health/health.decorator.ts:13-44 only attaches HEALTH_CHECK_METADATA and Cache-Control header metadata; it does not wire Swagger @ApiExtraModels/@ApiResponse schemas, and SwaggerModule.createDocument() in packages/swagger/src/swagger-module.ts does not inspect HEALTH_CHECK_METADATA (expected document.components.schemas to include ["TerminusHealthCheckResult", "TerminusHealthIndicatorResult"], received []).
    it.skip("registers the result and the indicator result as named schemas", () => {
      expect(Object.keys(document.components?.schemas ?? {})).toEqual(
        expect.arrayContaining([
          "TerminusHealthCheckResult",
          "TerminusHealthIndicatorResult",
        ]),
      );
    });

    for (const path of ["/health", "/ready"] as const) {
      // BUNEST_BUG: @HealthCheck() in packages/observability/src/health/health.decorator.ts:13-44 does not attach Swagger 200/503 response schemas referencing #/components/schemas/TerminusHealthCheckResult (received undefined for responseSchema(path, status).allOf).
      it.skip(`references the named schema from the 200 and 503 response of ${path}`, () => {
        for (const status of ["200", "503"] as const) {
          expect(responseSchema(path, status)?.allOf).toEqual([
            { $ref: "#/components/schemas/TerminusHealthCheckResult" },
          ]);
        }
      });
    }

    // BUNEST_BUG: @HealthCheck() in packages/observability/src/health/health.decorator.ts:13-44 does not emit 200 (["ok", "degraded"]) and 503 (["error", "shutting_down"]) response status enum schemas in OpenAPI output (received undefined).
    it.skip("keeps the ok/error status enums distinct per response", () => {
      expect(responseSchema("/health", "200")?.properties?.status?.enum).toEqual(
        ["ok", "degraded"],
      );
      expect(responseSchema("/health", "503")?.properties?.status?.enum).toEqual(
        ["error", "shutting_down"],
      );
    });

    // An indicator can add its own data to its result (#2516)
    // BUNEST_BUG: @HealthCheck() in packages/observability/src/health/health.decorator.ts:13-44 does not register TerminusHealthCheckResult / TerminusHealthIndicatorResult schemas with additionalProperties: true (received undefined).
    it.skip("allows additional properties on an indicator result", () => {
      const result: any = document.components?.schemas?.TerminusHealthCheckResult;

      expect(result?.properties?.details?.additionalProperties).toEqual({
        allOf: [
          { $ref: "#/components/schemas/TerminusHealthIndicatorResult" },
          { type: "object", additionalProperties: true },
        ],
      });
    });
  },
);
